#!/usr/bin/env node
// Org Intelligence — génère la ressource statique OrgIntelligenceUninstall (liste des composants du
// socle et des modules), lue par le bouton « Uninstall Org Intelligence » de Settings
// (OrgUninstallService, dossier source-tools/ : installation depuis les sources seulement). À relancer
// après tout ajout ou suppression de composant ; `--check` échoue
// si la ressource n'est plus à jour (lancé par npm run check:modules).
//
// Usage : node scripts/build-uninstall-manifest.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import { projectComponents, TOOLING_COMPONENTS } from "./lib/components.mjs";

const root = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  ".."
);
const dir = path.join(root, "source-tools/main/default/staticresources");
const file = path.join(dir, "OrgIntelligenceUninstall.json");

const group = (components) => {
  const byType = {};
  for (const [type, name] of components) (byType[type] ||= []).push(name);
  return byType;
};
const content = `${JSON.stringify(
  {
    description:
      "Org Intelligence components deleted by Settings > Uninstall. Generated by scripts/build-uninstall-manifest.mjs.",
    components: group(projectComponents(root)),
    tooling: TOOLING_COMPONENTS.map(([type, name]) => ({ type, name }))
  },
  null,
  2
)}\n`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (current !== content) {
    console.error(
      "✖ The uninstall manifest is out of date: run node scripts/build-uninstall-manifest.mjs"
    );
    process.exit(1);
  }
  console.log("✔ Uninstall manifest up to date");
  process.exit(0);
}

fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(file, content);
fs.writeFileSync(
  path.join(dir, "OrgIntelligenceUninstall.resource-meta.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>
<StaticResource xmlns="http://soap.sforce.com/2006/04/metadata">
    <cacheControl>Private</cacheControl>
    <contentType>application/json</contentType>
    <description>Org Intelligence: components deleted by Settings &gt; Uninstall (generated).</description>
</StaticResource>
`
);
const count = Object.values(JSON.parse(content).components).reduce(
  (sum, names) => sum + names.length,
  0
);
console.log(`✔ ${path.relative(root, file)}: ${count} components`);
